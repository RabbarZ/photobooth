#!/usr/bin/env python3
"""Rotate the WPA passphrase and regenerate the Wi-Fi join QR.

Why rotate at all: deauthenticating a device does not stop it reassociating a
second later. Changing the passphrase does. A guest whose session ended has to
rescan the QR, which is the whole gatekeeping mechanism -- so there is no MAC
blocklist anywhere in this system.

Overlapping key ring
--------------------
The passphrase lives in a `wpa_psk_file`, which accepts many wildcard-MAC lines
at once; hostapd authorises a station against any of them. Each rotation
prepends the new passphrase and trims the list to `valid_passphrases`, so a
code scanned a few rotations ago still works. Without that overlap, a guest who
joined moments before a rotation cannot reconnect after any transient drop --
power save, roaming, a wall -- and has no way to know why.

The ring is read back from the key file rather than kept in memory, so
restarting this service does not invalidate everyone's cached passphrase.

WHAT ROTATION DOES NOT DO: it does not evict anyone. A deauthenticated device
reassociates immediately on its cached key -- measured at about one second.
Rotation only affects devices re-authenticating after their key has aged out,
which hits innocent guests as readily as departing ones. Since the session
limits were removed, this ageing-out is the ONLY thing that ends a session.

CAVEAT: on hostapd 2.10, RELOAD_WPA_PSK returns OK and rereads the file, but the
daemon still deauthenticates stations so they re-key. Every rotation therefore
interrupts everyone briefly. Keep rotate_interval_minutes long; a very short
interval produces constant disconnects.
"""

from __future__ import annotations

import argparse
import logging
import os
import secrets
import signal
import sys
import tempfile
import time
from pathlib import Path

import pbcommon
import wifiqr

log = logging.getLogger("rotate")
_running = True

# Ambiguous glyphs removed: guests occasionally type this by hand when a
# camera will not scan, and 0/O/1/l/I are where that goes wrong.
ALPHABET = "abcdefghijkmnopqrstuvwxyzACDEFGHJKLMNPQRSTUVWXYZ23456789"

# hostapd's wpa_psk_file uses a per-MAC key list; this wildcard means "any MAC".
ANY_MAC = "00:00:00:00:00:00"


def _stop(_signum, _frame) -> None:
    global _running
    _running = False


def generate_passphrase(length: int) -> str:
    # WPA2 requires 8..63 printable ASCII characters.
    length = max(8, min(63, int(length)))
    return "".join(secrets.choice(ALPHABET) for _ in range(length))


def _write_atomic(path: Path, data: bytes, mode: int) -> None:
    """Replace `path` in one step so no reader ever sees a half-written file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def read_psk_ring(config: dict) -> list[str]:
    """Passphrases currently accepted, newest first.

    Parsed back out of the key file rather than kept in memory, so a restart
    of this service does not invalidate every guest's cached passphrase.
    """
    path = Path(config["password"]["psk_file"])
    ring: list[str] = []
    try:
        for line in path.read_text().splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            mac, _, secret = line.partition(" ")
            if mac == ANY_MAC and secret:
                ring.append(secret)
    except OSError:
        pass
    return ring


def write_psk_file(config: dict, passphrase: str) -> list[str]:
    """Prepend `passphrase` to the ring and write the trimmed result.

    hostapd's wpa_psk_file accepts many wildcard-MAC lines and will authorise
    a station against any of them, which is what makes overlap possible at
    all: the newest key is the one on the QR, while the previous few stay
    valid so a phone reconnecting on a cached passphrase is not locked out.
    """
    keep = max(1, int(config["password"].get("valid_passphrases", 1)))
    ring = [passphrase] + [p for p in read_psk_ring(config) if p != passphrase]
    ring = ring[:keep]

    lines = ["# Generated by rotate_password.py -- do not edit by hand.",
             "# Newest first; all of these are accepted by hostapd.",
             f"# valid_passphrases = {keep}"]
    lines += [f"{ANY_MAC} {secret}" for secret in ring]
    _write_atomic(Path(config["password"]["psk_file"]),
                  ("\n".join(lines) + "\n").encode(), 0o600)
    log.debug("psk ring now holds %d passphrase(s)", len(ring))
    return ring


def write_qr(config: dict, passphrase: str) -> Path:
    """Write the join QR to the fixed path the booth display renders."""
    return wifiqr.write_qr(Path(config["password"]["qr_path"]),
                           config["access_point"]["ssid"], passphrase)


def reload_hostapd(config: dict) -> bool:
    """Apply the new key file. True if no clients were dropped."""
    ok, out = pbcommon.hostapd_cli(config, "raw", "RELOAD_WPA_PSK")
    if ok:
        log.info("RELOAD_WPA_PSK ok (note: hostapd 2.10 still re-keys stations, so clients see a brief drop)")
        return True

    log.warning("RELOAD_WPA_PSK unavailable (%s)", out or "no output")
    ok, out = pbcommon.hostapd_cli(config, "reconfigure")
    if ok:
        log.warning("fell back to reconfigure -- ALL CONNECTED CLIENTS DROPPED")
    else:
        log.error("could not reload hostapd at all: %s", out or "no output")
    return False


def rotate_once(config: dict) -> str:
    passphrase = generate_passphrase(config["password"]["length"])
    ring = write_psk_file(config, passphrase)

    # Plain-text copy for the booth display / operator. 0600: this is the key
    # to the network, and the QR beside it is already the guest-facing path.
    _write_atomic(Path(config["password"]["password_path"]),
                  (passphrase + "\n").encode(), 0o600)

    reload_hostapd(config)
    qr_path = write_qr(config, passphrase)
    interval = float(config["password"]["rotate_interval_minutes"])
    log.info("rotated passphrase; %d key(s) valid (~%.0f min of overlap); QR at %s",
             len(ring), len(ring) * interval, qr_path)
    return passphrase


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--once", action="store_true",
                        help="rotate a single time and exit")
    parser.add_argument("--print", dest="show", action="store_true",
                        help="print the new passphrase to stdout (setup use)")
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO,
                        format="%(asctime)s %(levelname)s %(message)s")
    signal.signal(signal.SIGTERM, _stop)
    signal.signal(signal.SIGINT, _stop)

    config = pbcommon.load_config()

    if args.once:
        passphrase = rotate_once(config)
        if args.show:
            print(passphrase)
        return 0

    # Looping in-process rather than using a systemd timer keeps the interval
    # in the one central config file; a restart is enough to apply a change.
    interval = float(config["password"]["rotate_interval_minutes"]) * 60
    log.info("rotating every %.0f min", interval / 60)
    rotate_once(config)
    while _running:
        deadline = time.time() + interval
        while _running and time.time() < deadline:
            time.sleep(min(1.0, max(0.0, deadline - time.time())))
        if _running:
            try:
                rotate_once(config)
            except Exception:
                log.exception("rotation failed; keeping the current passphrase")
    log.info("stopped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
